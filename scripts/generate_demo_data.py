"""Reproducible fictional monthly observations and a genuine grid-table PDF."""

import csv
from pathlib import Path

import pymupdf

ROOT = Path(__file__).resolve().parents[1]
BUILDINGS = {
    "Academic Block A": [4100, 4200, 4500, 4800, 5200, 5600],
    "Academic Block B": [3500, 3450, 3400, 3300, 3200, 3100],
    "Boys Hostel": [4800, 4900, 5100, 5400, 5800, 6200],
    "Girls Hostel": [4600, 4700, 4800, 5000, 5300, 5500],
    "Library": [1800, 1750, 1700, 1650, 1600, 1550],
}
OCCUPANCY = {
    "Academic Block A": 800,
    "Academic Block B": 600,
    "Boys Hostel": 400,
    "Girls Hostel": 350,
    "Library": "",
}


def generate(directory: Path = ROOT / "data") -> None:
    directory.mkdir(parents=True, exist_ok=True)
    rows = [
        [building, f"2026-{month:02d}", values[month - 1], OCCUPANCY[building]]
        for month in range(1, 7)
        for building, values in BUILDINGS.items()
    ]
    headers = ["building_name", "month", "electricity_kwh", "occupancy"]
    with (directory / "campus_electricity_sample.csv").open(
        "w", newline="", encoding="utf-8"
    ) as file:
        writer = csv.writer(file, lineterminator="\n")
        writer.writerow(headers)
        writer.writerows(rows)
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    page.insert_text((40, 35), "CampusPulse | Campus electricity report", fontsize=16)
    page.insert_text((40, 57), "SYNTHETIC DEMONSTRATION DATA", fontsize=11, color=(0, 0.45, 0.45))
    page.insert_text(
        (40, 74),
        "Fictional pilot context: IIMT University, Meerut. No affiliation or official data.",
        fontsize=8,
    )
    all_rows = [headers, *rows]
    xs, top, height = [40, 235, 335, 460, 555], 95, 21
    for index, row in enumerate(all_rows):
        y = top + index * height
        if index == 0:
            page.draw_rect(
                pymupdf.Rect(xs[0], y, xs[-1], y + height), color=None, fill=(0.88, 0.95, 0.94)
            )
        for col, value in enumerate(row):
            page.insert_text((xs[col] + 6, y + 14), str(value), fontsize=9)
    for x in xs:
        page.draw_line((x, top), (x, top + len(all_rows) * height), width=0.6)
    for i in range(len(all_rows) + 1):
        page.draw_line((xs[0], top + i * height), (xs[-1], top + i * height), width=0.6)
    page.insert_text(
        (40, 785),
        "Units: kWh; occupancy = students. Library occupancy is intentionally unavailable.",
        fontsize=8,
    )
    page.insert_text(
        (40, 800),
        "Values generated by scripts/generate_demo_data.py. Not a real university report.",
        fontsize=8,
    )
    doc.set_metadata(
        {
            "title": "SYNTHETIC DEMONSTRATION DATA - CampusPulse",
            "author": "CampusPulse demo generator",
        }
    )
    doc.save(directory / "campus_electricity_sample.pdf", deflate=True)
    doc.close()
    # A second 2026 H2 fictional dataset plus an overlapping-month version.
    for suffix, months in (("_h2", range(7, 13)), ("_overlap", range(1, 7))):
        variant_rows = []
        for month in months:
            for building, values in BUILDINGS.items():
                # Deliberately different readings, so comparisons have real deltas.
                reference = values[(month - 1) % 6]
                variant_rows.append([building, f"2026-{month:02d}",
                                     int(round(reference * 1.07 + 50)), OCCUPANCY[building]])
        with (directory / f"campus_electricity_sample{suffix}.csv").open(
            "w", newline="", encoding="utf-8") as file:
            writer = csv.writer(file, lineterminator="\n")
            writer.writerow(headers)
            writer.writerows(variant_rows)
        pdf = pymupdf.open()
        sheet = pdf.new_page(width=595, height=842)
        sheet.insert_text((40, 35), f"CampusPulse | Synthetic report {suffix}", fontsize=15)
        sheet.insert_text((40, 55), "SYNTHETIC DEMONSTRATION DATA - NOT OFFICIAL", fontsize=10)
        all_variant_rows = [headers, *variant_rows]
        for index, row in enumerate(all_variant_rows):
            y = 95 + index * 21
            for col, value in enumerate(row):
                sheet.insert_text((xs[col] + 5, y + 14), str(value), fontsize=9)
        for x in xs:
            sheet.draw_line((x, 95), (x, 95 + len(all_variant_rows) * 21), width=.6)
        for i in range(len(all_variant_rows) + 1):
            sheet.draw_line((xs[0], 95 + i * 21), (xs[-1], 95 + i * 21), width=.6)
        sheet.insert_text((40, 785), "Invented values only; no official campus data.", fontsize=9)
        pdf.save(directory / f"campus_electricity_sample{suffix}.pdf", deflate=True)
        pdf.close()


if __name__ == "__main__":
    generate()
    print("Generated synthetic CSV and table PDF in data/.")
