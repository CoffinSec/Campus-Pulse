"""Reproducible fictional monthly observations and a genuine grid-table PDF."""

import csv
from pathlib import Path

import pymupdf

ROOT = Path(__file__).resolve().parents[1]
BUILDINGS = {
    "Academic Block A": [4100, 4200, 4500, 4800, 5200, 5600],
    "Academic Block B": [3500, 3450, 3400, 3300, 3200, 3100],
    "Boys Hostel": [4800, 4900, 5100, 5400, 5800, 6200],
    "Girls Hostel": [4600, 4700, 4800, 5000, 5300, 5500],
    "Library": [1800, 1750, 1700, 1650, 1600, 1550],
}


def generate(directory: Path = ROOT / "data") -> None:
    directory.mkdir(parents=True, exist_ok=True)
    rows = [
        [building, f"2026-{month:02d}", values[month - 1]]
        for month in range(1, 7)
        for building, values in BUILDINGS.items()
    ]
    headers = ["building_name", "month", "electricity_kwh"]
    with (directory / "campus_electricity_sample.csv").open(
        "w", newline="", encoding="utf-8"
    ) as file:
        writer = csv.writer(file, lineterminator="\n")
        writer.writerow(headers)
        writer.writerows(rows)
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    page.insert_text((40, 35), "CampusPulse | Campus electricity report", fontsize=16)
    page.insert_text((40, 57), "SYNTHETIC DEMONSTRATION DATA", fontsize=11, color=(0, 0.45, 0.45))
    page.insert_text(
        (40, 74),
        "Fictional pilot context: IIMT University, Meerut. No affiliation or official data.",
        fontsize=8,
    )
    all_rows = [headers, *rows]
    xs, top, height = [40, 270, 390, 555], 95, 21
    for index, row in enumerate(all_rows):
        y = top + index * height
        if index == 0:
            page.draw_rect(
                pymupdf.Rect(xs[0], y, xs[-1], y + height), color=None, fill=(0.88, 0.95, 0.94)
            )
        for col, value in enumerate(row):
            page.insert_text((xs[col] + 6, y + 14), str(value), fontsize=9)
    for x in xs:
        page.draw_line((x, top), (x, top + len(all_rows) * height), width=0.6)
    for i in range(len(all_rows) + 1):
        page.draw_line((xs[0], top + i * height), (xs[-1], top + i * height), width=0.6)
    page.insert_text(
        (40, 785),
        "Unit: kWh. One observation per fictional building per month. January-June 2026.",
        fontsize=8,
    )
    page.insert_text(
        (40, 800),
        "Values generated by scripts/generate_demo_data.py. Not a real university report.",
        fontsize=8,
    )
    doc.set_metadata(
        {
            "title": "SYNTHETIC DEMONSTRATION DATA - CampusPulse",
            "author": "CampusPulse demo generator",
        }
    )
    doc.save(directory / "campus_electricity_sample.pdf", deflate=True)
    doc.close()


if __name__ == "__main__":
    generate()
    print("Generated synthetic CSV and table PDF in data/.")
